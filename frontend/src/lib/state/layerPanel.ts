import { get } from "svelte/store";
import { applyDocumentSnapshot, document, type DocLayer } from "./document";
import { workspace } from "./workspace";

export interface LayerDropIntent {
  layerID: string;
  targetID: string;
  placement: "before" | "after" | "inside";
}

/** Top-first siblings, with a folder preceding its descendants. */
export function layerPanelRows(layers: readonly DocLayer[]): { layer: DocLayer; depth: number }[] {
  const rows: { layer: DocLayer; depth: number }[] = [];
  const seen = new Set<string>();
  function visit(parent: string | null, depth: number): void {
    for (const layer of [...layers].reverse()) {
      if (layer.parentID !== parent || seen.has(layer.id)) continue;
      seen.add(layer.id);
      rows.push({ layer, depth });
      if (layer.isGroup) visit(layer.id, depth + 1);
    }
  }
  visit(null, 0);
  return rows;
}

export function layerDropIntent(layers: readonly DocLayer[], sourceID: string, targetID: string,
  y: number, height: number): LayerDropIntent | null {
  const source = layers.find((l) => l.id === sourceID);
  const target = layers.find((l) => l.id === targetID);
  if (!source || !target || sourceID === targetID || height <= 0) return null;
  // Dropping a folder anywhere in its descendants would create a cycle.
  const seen = new Set<string>();
  for (let parent = target.parentID; parent; parent = layers.find((l) => l.id === parent)?.parentID ?? null) {
    if (parent === sourceID || seen.has(parent)) return null;
    seen.add(parent);
  }
  const placement = target.isGroup && y >= height * .25 && y <= height * .75
    ? "inside" : y < height * .5 ? "before" : "after";
  return { layerID: sourceID, targetID, placement };
}

/** The outer option owns selection; native controls own their keyboard events. */
export function isLayerPanelChildEventTarget(event: Event): boolean {
  return event.target instanceof Element && !!event.target.closest("button,input,select,label,[data-panel-control]");
}

/** Tab-bound atomic placement, including subtree and clipping repair. */
export async function placeLayer(tabID: string, intent: LayerDropIntent): Promise<void> {
  // Kept here until Wails bindings are regenerated by the integration owner.
  const bridge = (window as unknown as { go: { bridge: { Service: {
    PlaceLayer(tab: string, layer: string, target: string, placement: string): Promise<string>;
  } } } }).go.bridge.Service;
  const raw = await bridge.PlaceLayer(tabID, intent.layerID, intent.targetID, intent.placement);
  if (get(workspace).activeId === tabID && get(document).docId === tabID) applyDocumentSnapshot(raw, tabID);
}
